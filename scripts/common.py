"""수집 스크립트 공용: 업체명·공고명 정규화"""
import re

_CO = re.compile(r'주식회사|유한회사|재단법인|사단법인|\(주\)|\(유\)|\(재\)|\(사\)|㈜')


def nz(s):
    """업체명 비교용: 회사 형태 표기·공백·기호 제거"""
    return re.sub(r'[^0-9A-Za-z가-힣]', '', _CO.sub('', str(s or ''))).lower()


def ntitle(s):
    """공고명 비교용 (엑셀 F열 규칙): 공백·특수문자, 연도, 긴급, 용역, 수의시담, 변경, 재공고, 협상 제거"""
    s = re.sub(r'[^0-9A-Za-z가-힣]', '', str(s or ''))
    s = re.sub(r'(19|20)\d{2}년?도?', '', s)
    for w in ('수의시담', '재공고', '긴급', '용역', '변경', '협상'):
        s = s.replace(w, '')
    return s.lower()
